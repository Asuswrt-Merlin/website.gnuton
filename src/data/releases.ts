/**
 * Firmware release history for the changelog.
 *
 * `github-releases.json` is refreshed by scripts/fetch-github-stats.mjs. The
 * committed snapshot keeps the site build offline-friendly, exactly like the
 * GitHub stats file. Current firmware lines get their own URL segment
 * (`/changelog/3004/<tag>/`); older 384/388 builds are grouped as `legacy`.
 */
import { marked } from 'marked';
import snapshot from './github-releases.json';

export type ChangelogBranch = '3006' | '3004' | '386' | 'legacy';

export interface FirmwareAsset {
  name: string;
  url: string;
  /** Size in bytes. */
  size: number;
  /** MD5 checksum from the manifest or companion `.md5` asset, when available. */
  md5?: string;
  /** SHA-256 from the manifest or the GitHub API asset digest, when available. */
  sha256?: string;
  /** Packaging prefix from the manifest, e.g. "GT-BE98". */
  model?: string;
  /** Theme key: "default", "tuf", "rog", or a future key. */
  variant?: string;
}

export interface ChangelogRelease {
  tag: string;
  name: string;
  /** GitHub release page, used for assets, checksums and build logs. */
  url: string;
  publishedAt: string;
  repository: string;
  branch: ChangelogBranch;
  prerelease: boolean;
  body: string;
  /** Firmware images, checksums, build logs and changelogs attached to the release. */
  assets: FirmwareAsset[];
}

const isChangelogBranch = (value: string): value is ChangelogBranch =>
  value === '3006' || value === '3004' || value === '386' || value === 'legacy';

/**
 * The committed JSON is generated by `pnpm stats`; the optional manifest
 * fields are not present in older snapshots, so widen the inferred type here.
 */
type SnapshotAsset = (typeof snapshot.releases)[number]['assets'][number] & {
  sha256?: string;
  model?: string;
  variant?: string;
};

const normalizeAsset = (asset: SnapshotAsset): FirmwareAsset => ({
  name: asset.name,
  url: asset.url,
  size: asset.size,
  ...(asset.md5 ? { md5: asset.md5 } : {}),
  ...(asset.sha256 ? { sha256: asset.sha256 } : {}),
  ...(asset.model ? { model: asset.model } : {}),
  ...(asset.variant ? { variant: asset.variant } : {}),
});

const normalizeRelease = (
  release: (typeof snapshot.releases)[number],
): ChangelogRelease => ({
  tag: release.tag,
  name: release.name,
  url: release.url,
  publishedAt: release.publishedAt,
  repository: release.repository,
  branch: isChangelogBranch(release.branch) ? release.branch : 'legacy',
  prerelease: release.prerelease,
  body: release.body,
  assets: (release.assets as SnapshotAsset[]).map(normalizeAsset),
});

export const changelogReleases: ChangelogRelease[] = snapshot.releases
  .map(normalizeRelease)
  .sort((a, b) => Date.parse(b.publishedAt) - Date.parse(a.publishedAt));

export const changelogReleasesFor = (branch: ChangelogBranch): ChangelogRelease[] =>
  changelogReleases.filter((release) => release.branch === branch);

export const findChangelogRelease = (tag: string): ChangelogRelease | undefined =>
  changelogReleases.find((release) => release.tag === tag);

export const changelogPath = (
  release: Pick<ChangelogRelease, 'branch' | 'tag'>,
): string => `/changelog/${release.branch}/${release.tag}/`;

/** Keep the descending release order while grouping entries by year. */
export const groupReleasesByYear = (
  releases: ChangelogRelease[],
): Array<[number, ChangelogRelease[]]> => {
  const byYear = new Map<number, ChangelogRelease[]>();

  for (const release of releases) {
    const year = new Date(release.publishedAt).getUTCFullYear();
    const group = byYear.get(year);

    if (group) {
      group.push(release);
    } else {
      byYear.set(year, [release]);
    }
  }

  return [...byYear.entries()];
};

/**
 * GitHub release bodies start with their own changelog heading and a
 * Date/Release block. The page header labels the published date and tag, so
 * drop the duplicate preamble before rendering the notes. Some releases put
 * tester notes before the metadata, so strip the Date/Release lines wherever
 * they appear.
 */
const CHANGELOG_HEADING =
  /^[ \t]*#+[ \t]*GNUton'?s Asus Merlin changelog[ \t]*#*[ \t]*(?:\r?\n)+/i;
const CHANGELOG_DATE = /^[ \t]*Date:[^\r\n]*(?:\r?\n)?/gim;
const CHANGELOG_RELEASE = /^[ \t]*Release:[^\r\n]*(?:\r?\n)?/gim;

/**
 * Normalise the ad-hoc indentation in older release notes. GitHub release
 * bodies often use one or two spaces for "top-level" bullets, and Marked
 * treats mixed indentation as nested lists. Remove the largest indent used by
 * a 0-3-space list marker from every line, clamping at zero. This keeps any
 * genuinely deeper indentation (continuations and nested lists) intact.
 */
function normalizeIndentation(text: string): string {
  const lines = text.replace(/\r\n?/g, '\n').split('\n');
  const nonEmpty = lines.filter((line) => line.trim() !== '');
  const listIndents = nonEmpty
    .map((line) => line.match(/^([ \t]*)(?:[-*+]|\d+[.)])\s+/))
    .filter((match): match is RegExpMatchArray => match !== null)
    .map((match) => match[1].length)
    .filter((indent) => indent <= 3);
  const margins = nonEmpty.map(
    (line) => line.match(/^[ \t]*/)?.[0].length ?? 0,
  );
  const margin =
    listIndents.length > 0
      ? Math.max(...listIndents)
      : margins.length > 0
        ? Math.min(...margins)
        : 0;

  const normalized = lines.map((line) => {
    const indent = line.match(/^[ \t]*/)?.[0].length ?? 0;
    return line.slice(Math.min(margin, indent));
  });

  // Drop only blank lines; trimming the string would remove the first
  // bullet's indentation and make Marked treat its siblings as children.
  while (normalized.length > 0 && normalized[0].trim() === '') normalized.shift();
  while (
    normalized.length > 0 &&
    normalized[normalized.length - 1].trim() === ''
  ) {
    normalized.pop();
  }

  return normalized.join('\n');
}

export function releaseNotesBody(release: ChangelogRelease): string {
  const notes = release.body
    .trimStart()
    .replace(CHANGELOG_HEADING, '')
    .replace(CHANGELOG_DATE, '')
    .replace(CHANGELOG_RELEASE, '');

  return normalizeIndentation(notes);
}

/**
 * Render a release body for the changelog and the firmware download dialog.
 * Release notes are trusted project content; external links open in a new tab.
 */
export function renderReleaseNotes(release: ChangelogRelease): string {
  const notes = releaseNotesBody(release);
  if (!notes) return '';

  return marked
    .parse(notes, { async: false, gfm: true })
    .replace(
      /<a href="(https?:\/\/[^"]+)"/g,
      '<a href="$1" target="_blank" rel="noopener"',
    );
}
